//! Доменные ошибки синхронизации. Границы соответствуют HTTP-статусам протокола
//! v1: сетевые/статусные сбои — [`SyncError::Http`], битый ответ сервера —
//! [`SyncError::Protocol`], предусловие `X-If-Hash` не совпало —
//! [`SyncError::Conflict`], лимиты 413/507 — [`SyncError::Limit`].

#[derive(thiserror::Error, Debug)]
pub enum SyncError {
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
    /// Сетевая ошибка или неожиданный HTTP-статус (текст безопасен для показа).
    #[error("http: {0}")]
    Http(String),
    /// Ответ сервера не соответствует протоколу (не разобрался JSON/поля).
    #[error("протокол: {0}")]
    Protocol(String),
    /// Код доступа не проходит строгую проверку формата (сервер вернул бы 401).
    #[error("код доступа неверного формата")]
    BadCode,
    /// Предусловие записи не выполнено — на сервере другая версия файла.
    #[error("конфликт")]
    Conflict { server_hash: Option<String> },
    /// Превышен лимит: файл >20 МБ (413) или хранилище >2 ГБ (507).
    #[error("лимит: {0}")]
    Limit(String),
    /// Локальная валидация (путь/аргумент); на сервере это 400.
    #[error("валидация: {0}")]
    Validation(String),
}

pub type SyncResult<T> = Result<T, SyncError>;
